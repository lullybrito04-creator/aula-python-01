escolha = int(input("Informe um numero de 1 a 7 para saber o dia da semana: "))

match escolha:
    case 1:
        print("domingo")
    case 2:
        print("segunda_feira")
    case 3:
        print("terça_feira")
    case 4:
        print("quarta_feira")
    case 5:
        print("quinta_feira")
    case 6:
        print("sexta feira")
    case 7:
        print("sabado")
   
